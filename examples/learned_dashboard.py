"""Learn a content-aware dashboard layout across viewports.

Run: python -m examples.learned_dashboard --steps 80

The reference layouts are generated by a transparent sizing rule, not human
preference data. Training uses SDF and image losses plus soft geometry losses.
"""

import argparse
import json
import math
from contextlib import ExitStack
from dataclasses import dataclass
from pathlib import Path

from PIL import Image, ImageDraw

from sdf_ui import Canvas, color, input_value, sdf
from sdf_ui.graph import GraphCase, GraphDatasetTrainer
from sdf_ui.learning import Bounds, Element, GaussianPolicy, Layout, Objective

HEIGHT = 72
MARGIN = 8
GAP = 6
CARD_Y = 9
CARD_HEIGHT = 38
MIN_BASE = 10
NAMES = ("overview", "trend", "details")
COLORS = ("#357db1", "#437e72", "#a66d52")
TRAIN = (
    ("train_compact", 120, (12, 20, 32)),
    ("train_medium", 144, (32, 12, 20)),
    ("train_wide", 168, (20, 32, 12)),
    ("train_balanced", 192, (18, 22, 24)),
)
HELD_OUT = (
    ("test_compact", 132, (20, 14, 30)),
    ("test_wide", 180, (14, 30, 20)),
)
VALIDATION = ("validation", 156, (24, 16, 24))


@dataclass
class Scenario:
    name: str
    width: int
    content: tuple
    graph: object
    visual: object
    reference: object
    layout: Layout
    case: GraphCase


def reference_widths(width, content):
    """Minimum content width plus equal share of spare space."""
    available = width - 2 * MARGIN - 2 * GAP
    minimums = [value + 6 for value in content]
    spare = available - sum(minimums)
    if spare < 0:
        raise ValueError("Scenario cannot fit its content in a single row")
    return tuple(value + spare / 3 for value in minimums)


def predict(policy, width, content):
    """Return named pixel bounds from a trained policy without a GPU context."""
    if isinstance(width, bool) or not isinstance(width, int) or width <= 0:
        raise ValueError("viewport width must be a positive integer")
    content = tuple(content)
    if len(content) != 3 or any(
        isinstance(v, bool) or not isinstance(v, int) or v <= 0 for v in content
    ):
        raise ValueError("content must contain three positive integer widths")
    reference_widths(width, content)
    action = policy.deterministic_action([width / 160, *(v / 32 for v in content)])
    shares = [
        max(float(value), 0) + math.log1p(math.exp(-abs(float(value)))) + 0.01
        for value in action
    ]
    available = width - 2 * MARGIN - 2 * GAP
    widths = [
        MIN_BASE + (available - 3 * MIN_BASE) * value / sum(shares) for value in shares
    ]
    return dict(zip(NAMES, boxes(widths)))


def boxes(widths):
    x = MARGIN
    result = []
    for width in widths:
        result.append(Bounds(x, CARD_Y, width, CARD_HEIGHT))
        x = x + width + GAP
    return result


def make_layout(width, content, card_bounds, *, inputs=None):
    """Describe the card and measured-content constraints for a viewport."""
    elements = [Element("panel", Bounds(0, 0, width, HEIGHT), role="panel")]
    for name, box, length in zip(NAMES, card_bounds, content):
        elements.append(
            Element(
                name,
                box,
                role="card",
                parent="panel",
                minimum_size=(length + 6, 20),
                content_bounds=Bounds(box.x + 3, CARD_Y + 11, length, 4),
            )
        )
    return Layout(elements, (width, HEIGHT), inputs={} if inputs is None else inputs)


def make_scene(bounds, content):
    """Create SDF card fields and a rendered dashboard preview."""
    fields = [
        Element(name, box).shape(corner_radius=4) for name, box in zip(NAMES, bounds)
    ]
    scene = color.clear("#111c2a")
    header = sdf.rect((28, HEIGHT - 10), (20, 2), corner_radius=2)
    scene = scene.over(header.fill("#a2b4c6", (0, 0, 0, 0)))
    for field, box, length, tint in zip(fields, bounds, content, COLORS):
        scene = scene.over(field.fill(tint, (0, 0, 0, 0)))
        # Content bars represent measured content. They deliberately are not
        # clipped, so content that does not fit is visible in the preview.
        bar = sdf.rect(
            (box.x + 3 + length / 2, CARD_Y + 13), (length / 2, 2), corner_radius=2
        )
        scene = scene.over(bar.fill("#e8f1f3", (0, 0, 0, 0)))
    return fields, scene.to_rgb()


def setup_case(canvas, stack, policy, spec):
    name, width, content = spec
    viewport = input_value("viewport")
    lengths = tuple(input_value(f"content_{i}") for i in range(3))
    logits = policy.mean_expressions([viewport / 160, *(v / 32 for v in lengths)])
    shares = tuple(value.softplus() + 0.01 for value in logits)
    available = viewport - 2 * MARGIN - 2 * GAP
    widths = tuple(
        MIN_BASE + (available - 3 * MIN_BASE) * share / sum(shares) for share in shares
    )
    learned_boxes = boxes(widths)
    fields, scene = make_scene(learned_boxes, lengths)
    reference_boxes = boxes(reference_widths(width, content))
    reference_fields, reference_scene = make_scene(reference_boxes, content)
    inputs = {"viewport": width, **{f"content_{i}": v for i, v in enumerate(content)}}

    # Train only the needed field/image roots; the richer preview graph is
    # executed for exports, keeping the per-step workload focused.
    highlight = fields[0].fill("#357db1", "#111c2a").to_rgb()
    target_highlight = reference_fields[0].fill("#357db1", "#111c2a").to_rgb()
    roots = {**dict(zip(NAMES, fields)), "highlight": highlight}
    graph = stack.enter_context(
        canvas.compile(roots, size=(width, HEIGHT), inputs=inputs)
    )
    visual = stack.enter_context(
        canvas.compile({"image": scene}, size=(width, HEIGHT), inputs=inputs)
    )
    reference = stack.enter_context(
        canvas.compile({"image": reference_scene}, size=(width, HEIGHT))
    )
    layout = make_layout(width, lengths, learned_boxes, inputs=graph.inputs)
    objective = Objective()
    for label, field in zip(NAMES, reference_fields):
        target = stack.enter_context(canvas.capture(field, size=(width, HEIGHT)))
        objective.mse(label, target, weight=1 / width**2, name=f"shape:{label}")
    target = stack.enter_context(canvas.capture(target_highlight, size=(width, HEIGHT)))
    objective.mse("highlight", target, weight=0.15, name="appearance")

    def constraints():
        return (
            layout.minimum_size_loss()
            + layout.content_overflow_loss()
            + layout.containment_loss()
            + layout.offscreen_loss()
            + layout.overlap_loss()
        ) / width**2

    objective.geometry(
        constraints,
        weight=3,
        name="constraints",
        identity={
            "kind": "dashboard",
            "version": 1,
            "width": width,
            "content": list(content),
            "margin": MARGIN,
            "gap": GAP,
        },
    )
    return Scenario(
        name,
        width,
        content,
        graph,
        visual,
        reference,
        layout,
        GraphCase(graph, objective, name),
    )


def metrics(scenario):
    with scenario.graph.run(scenario.case.objective) as execution:
        result = {"loss": execution.loss, "terms": dict(execution.metrics)}
    snapshot = scenario.layout.snapshot()
    result.update(
        {
            "viewport": [scenario.width, HEIGHT],
            "content_widths": list(scenario.content),
            "card_widths": [snapshot.bounds[name].width for name in NAMES],
            "reference_widths": list(
                reference_widths(scenario.width, scenario.content)
            ),
            "violations": scenario.layout.violations(tolerance=1e-6),
        }
    )
    return result


def save_preview(scenario, path, *, reference=False):
    graph = scenario.reference if reference else scenario.visual
    graph.save("image", path)
    # Labels are annotations, not differentiated or included in the loss.
    if reference:
        bounds = boxes(reference_widths(scenario.width, scenario.content))
    else:
        snapshot = scenario.layout.snapshot()
        bounds = [snapshot.bounds[name] for name in NAMES]
    with Image.open(path) as image:
        image = image.convert("RGBA")
        draw = ImageDraw.Draw(image)
        for label, box in zip(("A", "B", "C"), bounds):
            draw.text(
                (box.x + 3, HEIGHT - (box.y + box.height) + 3), label, fill="white"
            )
        image.save(path)


def comparison(scenarios, output):
    """Create a legible, labelled before/after/reference contact sheet."""
    scale, padding, label = 3, 12, 20
    cell_width = max(item.width for item in scenarios) * scale
    cell_height = HEIGHT * scale
    sheet = Image.new(
        "RGB",
        (
            3 * cell_width + 4 * padding,
            len(scenarios) * (cell_height + 2 * label + padding) + padding,
        ),
        "#e8edf0",
    )
    draw = ImageDraw.Draw(sheet)
    for row, scenario in enumerate(scenarios):
        top = padding + row * (cell_height + 2 * label + padding)
        draw.text(
            (padding, top),
            f"{scenario.name}  |  viewport {scenario.width} x {HEIGHT}  |  content {scenario.content}",
            fill="#18222c",
        )
        for column, phase in enumerate(("before", "after", "reference")):
            left = padding + column * (cell_width + padding)
            draw.text((left, top + label), phase.upper(), fill="#18222c")
            with Image.open(output / f"{scenario.name}_{phase}.png") as picture:
                sheet.paste(
                    picture.convert("RGB").resize(
                        (scenario.width * scale, cell_height), Image.Resampling.NEAREST
                    ),
                    (left, top + 2 * label),
                )
    sheet.save(output / "comparison.png")


def run(
    output,
    steps=80,
    seed=7,
    resume=None,
    scenarios=None,
    progress=None,
    patience=None,
    validation_interval=5,
    min_delta=1e-5,
    initial_policy=None,
):
    if isinstance(steps, bool) or not isinstance(steps, int) or steps < 0:
        raise ValueError("steps must be a nonnegative integer")
    if progress is not None and not callable(progress):
        raise TypeError("progress must be callable")
    if resume is not None and initial_policy is not None:
        raise ValueError("Choose either a trainer checkpoint or initial policy weights")
    custom = []
    for index, spec in enumerate(scenarios or (), 1):
        if len(spec) != 4 or any(
            isinstance(v, bool) or not isinstance(v, int) or v <= 0 for v in spec
        ):
            raise ValueError(
                "Custom scenarios require a positive viewport width and three positive content widths"
            )
        width, *content = spec
        reference_widths(width, content)
        custom.append((f"custom_{index}", width, tuple(content)))
    output = Path(output)
    output.mkdir(parents=True, exist_ok=True)
    policy = GaussianPolicy(obs_dim=4, action_dim=3, hidden_dim=8, seed=seed)
    if initial_policy is not None:
        policy.load_state_dict(
            json.loads(Path(initial_policy).read_text(encoding="utf-8"))
        )
    with Canvas((192, HEIGHT)) as canvas, ExitStack() as stack:
        validation_specs = (VALIDATION,) if patience is not None else ()
        scenarios = [
            setup_case(canvas, stack, policy, spec)
            for spec in (*TRAIN, *validation_specs, *HELD_OUT, *custom)
        ]
        training = scenarios[: len(TRAIN)]
        validation_cases = scenarios[len(TRAIN) : len(TRAIN) + len(validation_specs)]
        held_out = scenarios[len(TRAIN) + len(validation_specs) :]
        with GraphDatasetTrainer(
            [scenario.case for scenario in training], lr=0.025
        ) as trainer:
            if resume:
                try:
                    trainer.load(resume)
                except ValueError as error:
                    raise ValueError(
                        f"Cannot resume trainer checkpoint: {error}. "
                        "To keep exported policy weights with a new optimizer, "
                        "use --initial-policy with policy.json."
                    ) from error
            before = {scenario.name: metrics(scenario) for scenario in scenarios}
            for scenario in scenarios:
                save_preview(scenario, output / f"{scenario.name}_before.png")
                save_preview(
                    scenario, output / f"{scenario.name}_reference.png", reference=True
                )
            readbacks = sum(s.graph.backend.stats["image_readbacks"] for s in training)
            history = trainer.fit(
                steps,
                callback=progress,
                validation=(
                    lambda: trainer.evaluate(
                        [scenario.case for scenario in validation_cases]
                    )
                )
                if validation_cases
                else None,
                patience=patience,
                min_delta=min_delta,
                validation_interval=validation_interval,
            )
            training_readbacks = (
                sum(s.graph.backend.stats["image_readbacks"] for s in training)
                - readbacks
            )
            after = {scenario.name: metrics(scenario) for scenario in scenarios}
            for scenario in scenarios:
                save_preview(scenario, output / f"{scenario.name}_after.png")
            held_out_score = trainer.evaluate([scenario.case for scenario in held_out])
            trainer.save(output / "checkpoint.json")
            (output / "policy.json").write_text(
                json.dumps(policy.state_dict(), indent=2), encoding="utf-8"
            )
            report = {
                "description": "Synthetic content-aware dashboard; references use minimum content width plus equal spare space.",
                "initialization_seed": seed
                if resume is None and initial_policy is None
                else None,
                "resumed_from": None if resume is None else str(resume),
                "initial_policy": None
                if initial_policy is None
                else str(initial_policy),
                "steps": trainer.steps,
                "training_steps_requested": steps,
                "training_steps_this_run": len(history),
                "training_cases": [scenario.name for scenario in training],
                "validation_cases": [scenario.name for scenario in validation_cases],
                "held_out_cases": [scenario.name for scenario in held_out],
                "before": before,
                "after": after,
                "held_out_evaluation": held_out_score,
                "training_image_readbacks": training_readbacks,
                "first_training_loss": history[0]["loss"] if history else None,
                "last_training_loss": history[-1]["loss"] if history else None,
                "device": canvas.device_info,
            }
            (output / "metrics.json").write_text(
                json.dumps(report, indent=2), encoding="utf-8"
            )
            comparison([training[0], *validation_cases, *held_out], output)
            return report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--steps", type=int, default=80)
    parser.add_argument("--seed", type=int, default=7)
    parser.add_argument("--output", type=Path, default=Path("out/learning/dashboard"))
    parser.add_argument("--resume", type=Path)
    parser.add_argument(
        "--initial-policy",
        type=Path,
        help="Start a new optimizer from exported policy weights",
    )
    parser.add_argument(
        "--patience",
        type=int,
        help="Enable validation-based early stopping after this many non-improving evaluations",
    )
    parser.add_argument("--validation-interval", type=int, default=5)
    parser.add_argument("--min-delta", type=float, default=1e-5)
    parser.add_argument(
        "--policy", type=Path, help="Load an exported policy for CPU-only prediction"
    )
    parser.add_argument(
        "--predict",
        type=int,
        nargs=4,
        metavar=("WIDTH", "A", "B", "C"),
        help="Print bounds for a new scenario without rendering; requires --policy",
    )
    parser.add_argument(
        "--scenario",
        type=int,
        nargs=4,
        action="append",
        metavar=("WIDTH", "A", "B", "C"),
        help="Add a held-out viewport and three measured content widths; may be repeated",
    )
    args = parser.parse_args()
    if args.policy is not None or args.predict is not None:
        if args.policy is None or args.predict is None:
            parser.error("--policy and --predict must be supplied together")
        if args.resume is not None or args.scenario or args.initial_policy is not None:
            parser.error(
                "--policy/--predict cannot be combined with --resume, --initial-policy, or --scenario"
            )
        policy = GaussianPolicy(obs_dim=4, action_dim=3, hidden_dim=8)
        policy.load_state_dict(json.loads(args.policy.read_text(encoding="utf-8")))
        try:
            result = predict(policy, args.predict[0], args.predict[1:])
        except ValueError as error:
            parser.error(str(error))
        print(
            json.dumps(
                {
                    "cards": {
                        name: {
                            key: getattr(box, key)
                            for key in ("x", "y", "width", "height")
                        }
                        for name, box in result.items()
                    },
                    "violations": make_layout(
                        args.predict[0], args.predict[1:], result.values()
                    ).violations(tolerance=1e-6),
                },
                indent=2,
            )
        )
        return
    if args.steps < 0:
        parser.error("--steps must be nonnegative")
    if args.resume is not None and args.initial_policy is not None:
        parser.error("choose either --resume or --initial-policy")
    if args.patience is not None and args.patience < 1:
        parser.error("--patience must be positive")
    if (
        args.validation_interval < 1
        or not math.isfinite(args.min_delta)
        or args.min_delta < 0
    ):
        parser.error(
            "validation interval must be positive and min-delta must be finite and nonnegative"
        )

    def progress(result):
        if result["step"] == 1 or result["step"] % 10 == 0:
            validation = (
                f", validation loss {result['validation_loss']:.6f}"
                if "validation_loss" in result
                else ""
            )
            print(
                f"step {result['step']}: training loss {result['loss']:.6f}{validation}",
                flush=True,
            )

    for scenario in args.scenario or ():
        if any(value <= 0 for value in scenario):
            parser.error("scenario widths must be positive")
        try:
            reference_widths(scenario[0], scenario[1:])
        except ValueError as error:
            parser.error(str(error))
    report = run(
        args.output,
        args.steps,
        args.seed,
        args.resume,
        args.scenario,
        progress,
        patience=args.patience,
        validation_interval=args.validation_interval,
        min_delta=args.min_delta,
        initial_policy=args.initial_policy,
    )
    print(
        json.dumps(
            {
                "training_loss": [
                    report["first_training_loss"],
                    report["last_training_loss"],
                ],
                "held_out_before": {
                    name: report["before"][name]["loss"]
                    for name in report["held_out_cases"]
                },
                "held_out_after": report["held_out_evaluation"]["cases"],
                "image_readbacks_during_training": report["training_image_readbacks"],
                "output": str(args.output.resolve()),
            },
            indent=2,
        )
    )


if __name__ == "__main__":
    main()
