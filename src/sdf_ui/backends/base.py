"""Backend-neutral ownership contract for materialized images."""

from abc import ABC, abstractmethod
from typing import Any, Protocol, runtime_checkable


def shape_size(shape):
    """Number of scalar components in an image port or uniform shape."""
    size = 1
    for extent in shape:
        size *= extent
    return size


@runtime_checkable
class RenderBackend(Protocol):
    """Device operations required by a compiled render graph.

    Buffers returned by ``create_buffer`` support read, write, clear and release.
    A backend owns its device resources; exported Images have independent
    lifetimes. This protocol does not imply a fallback or another implementation.
    """

    stats: dict
    device_info: dict

    def create_buffer(self, size: int) -> Any: ...
    def owns_context(self, context: Any) -> bool: ...
    def create_optimizer(self, parameters: Any, lr: float) -> Any: ...
    def mask_weight_sum(self, image: Any) -> float: ...
    def shader_fingerprints(self, name: str) -> tuple[str, str]: ...
    def defaults(self, name: str) -> Any: ...
    def uniforms(self, name: str, params: Any) -> Any: ...
    def clear_status(self) -> None: ...
    def check_status(self) -> None: ...
    def validate_images(self, images: Any) -> None: ...
    def import_texture(self, texture: Any, channels: int) -> Any: ...
    def display_image(self, image: Any, mode: Any = None) -> Any: ...
    def seed_pixel_loss(self, *args: Any) -> None: ...
    def forward(self, *args: Any) -> Any: ...
    def backward_into(self, *args: Any, **kwargs: Any) -> None: ...
    def upload(self, pixels: Any) -> Any: ...
    def copy_image(self, image: Any) -> Any: ...
    def close(self) -> None: ...


class Image(ABC):
    """An owned, explicitly readable image supplied by a rendering backend."""

    @abstractmethod
    def read(self):
        """Copy image data to host memory."""

    @abstractmethod
    def close(self):
        """Release owned resources."""
